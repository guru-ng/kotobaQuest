/**
 * Writes dist/sw.js after a Vite build.
 *
 * The precache list has to name the hashed asset files, which only exist once
 * Vite has run, so the worker is generated here rather than kept as a static
 * file. Generated content under /data is NOT precached (it is several MB):
 * it caches itself as each level is opened.
 *
 * Run: npx tsx scripts/build-sw.ts   (wired into `npm run build`)
 */
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';

const DIST = join(process.cwd(), 'dist');
if (!existsSync(DIST)) {
  console.error('dist/ not found — run vite build first.');
  process.exit(1);
}

const walk = (dir: string, base = ''): string[] =>
  readdirSync(dir).flatMap(name => {
    const full = join(dir, name);
    const rel = `${base}/${name}`;
    return statSync(full).isDirectory() ? walk(full, rel) : [rel];
  });

const all = walk(DIST);
const precache = [
  '/',
  ...all.filter(
    p =>
      p.startsWith('/assets/') ||
      ['/favicon.svg', '/icon-192.png', '/icon-512.png', '/manifest.webmanifest'].includes(p)
  )
];

// Any change to the shell changes the version, which retires the old cache
const version = createHash('sha256').update(precache.join('|')).digest('hex').slice(0, 12);

const sw = `/* Generated by scripts/build-sw.ts — do not edit. */
const VERSION = ${JSON.stringify(version)};
const SHELL = 'kq-shell-' + VERSION;
const DATA = 'kq-data-v1';
const FONTS = 'kq-fonts-v1';
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener('install', event => {
  event.waitUntil(caches.open(SHELL).then(cache => cache.addAll(PRECACHE)));
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(
      keys.filter(k => k.startsWith('kq-shell-') && k !== SHELL).map(k => caches.delete(k))
    );
    await self.clients.claim();
  })());
});

// The page asks for the update only once the user accepts it
self.addEventListener('message', event => {
  if (event.data === 'SKIP_WAITING') self.skipWaiting();
});

// Servers send 'Vary: Origin' and Vite loads its assets with crossorigin, so
// the request carries an Origin header the precache fetch did not. Without
// ignoreVary the Cache API refuses the match and offline silently breaks.
const MATCH = { ignoreVary: true };

async function cacheFirst(request, cacheName) {
  const cache = await caches.open(cacheName);
  const hit = await cache.match(request, MATCH);
  if (hit) return hit;
  const response = await fetch(request);
  if (response.ok) cache.put(request, response.clone());
  return response;
}

/** Serve the cached copy at once, refresh it in the background. */
async function staleWhileRevalidate(request, cacheName) {
  const cache = await caches.open(cacheName);
  const hit = await cache.match(request, MATCH);
  const network = fetch(request)
    .then(response => {
      if (response.ok) cache.put(request, response.clone());
      return response;
    })
    .catch(() => undefined);
  const response = hit || (await network);
  if (response) return response;
  return new Response('Offline and not cached', { status: 504, statusText: 'Offline' });
}

self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;

  let url;
  try {
    url = new URL(request.url);
  } catch {
    return;
  }

  // Navigations: try the network so a new build is picked up, fall back to the shell
  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      try {
        return await fetch(request);
      } catch {
        const cache = await caches.open(SHELL);
        return (await cache.match('/index.html', MATCH)) || (await cache.match('/', MATCH)) ||
          new Response('Offline', { status: 503 });
      }
    })());
    return;
  }

  if (url.origin === self.location.origin) {
    // Hashed filenames never change contents
    if (url.pathname.startsWith('/assets/')) {
      event.respondWith(cacheFirst(request, SHELL));
      return;
    }
    // Vocabulary, kanji and puzzle data: cached as each level is opened
    if (url.pathname.startsWith('/data/')) {
      event.respondWith(staleWhileRevalidate(request, DATA));
      return;
    }
    event.respondWith(staleWhileRevalidate(request, SHELL));
    return;
  }

  if (url.hostname === 'fonts.googleapis.com' || url.hostname === 'fonts.gstatic.com') {
    event.respondWith(cacheFirst(request, FONTS));
  }
  // Anything else (photo CDNs, analytics) goes straight to the network.
});
`;

writeFileSync(join(DIST, 'sw.js'), sw);
const kb = (readFileSync(join(DIST, 'sw.js')).length / 1024).toFixed(1);
console.log(`dist/sw.js  ${kb} kB  version ${version}  precaching ${precache.length} files`);
